def test_concat_datetime_timezone(self):
    idx1 = pd.date_range('2011-01-01', periods=3, freq='H', tz='Europe/Paris')
    idx2 = pd.date_range(start=idx1[0], end=idx1[-1], freq='H')
    df1 = pd.DataFrame({'a': [1, 2, 3]}, index=idx1)
    df2 = pd.DataFrame({'b': [1, 2, 3]}, index=idx2)
    result = pd.concat([df1, df2], axis=1)
    exp_idx = DatetimeIndex(['2011-01-01 00:00:00+01:00', '2011-01-01 01:00:00+01:00', '2011-01-01 02:00:00+01:00'], freq='H').tz_convert('UTC').tz_convert('Europe/Paris')
    expected = pd.DataFrame([[1, 1], [2, 2], [3, 3]], index=exp_idx, columns=['a', 'b'])
    tm.assert_frame_equal(result, expected)
    idx3 = pd.date_range('2011-01-01', periods=3, freq='H', tz='Asia/Tokyo')
    df3 = pd.DataFrame({'b': [1, 2, 3]}, index=idx3)
    result = pd.concat([df1, df3], axis=1)
    exp_idx = DatetimeIndex(['2010-12-31 15:00:00+00:00', '2010-12-31 16:00:00+00:00', '2010-12-31 17:00:00+00:00', '2010-12-31 23:00:00+00:00', '2011-01-01 00:00:00+00:00', '2011-01-01 01:00:00+00:00'])
    expected = pd.DataFrame([[np.nan, 1], [np.nan, 2], [np.nan, 3], [1, np.nan], [2, np.nan], [3, np.nan]], index=exp_idx, columns=['a', 'b'])
    tm.assert_frame_equal(result, expected)
    result = pd.concat([df1.resample('H').mean(), df2.resample('H').mean()], sort=True)
    expected = pd.DataFrame({'a': [1, 2, 3] + [np.nan] * 3, 'b': [np.nan] * 3 + [1, 2, 3]}, index=idx1.append(idx1))
    tm.assert_frame_equal(result, expected)