def test_datetime64_tz_fillna(self):
    for tz in ['US/Eastern', 'Asia/Tokyo']:
        s = Series([Timestamp('2011-01-01 10:00'), pd.NaT, Timestamp('2011-01-03 10:00'), pd.NaT])
        null_loc = pd.Series([False, True, False, True])
        result = s.fillna(pd.Timestamp('2011-01-02 10:00'))
        expected = Series([Timestamp('2011-01-01 10:00'), Timestamp('2011-01-02 10:00'), Timestamp('2011-01-03 10:00'), Timestamp('2011-01-02 10:00')])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna(pd.Timestamp('2011-01-02 10:00', tz=tz))
        expected = Series([Timestamp('2011-01-01 10:00'), Timestamp('2011-01-02 10:00', tz=tz), Timestamp('2011-01-03 10:00'), Timestamp('2011-01-02 10:00', tz=tz)])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna('AAA')
        expected = Series([Timestamp('2011-01-01 10:00'), 'AAA', Timestamp('2011-01-03 10:00'), 'AAA'], dtype=object)
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna({1: pd.Timestamp('2011-01-02 10:00', tz=tz), 3: pd.Timestamp('2011-01-04 10:00')})
        expected = Series([Timestamp('2011-01-01 10:00'), Timestamp('2011-01-02 10:00', tz=tz), Timestamp('2011-01-03 10:00'), Timestamp('2011-01-04 10:00')])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna({1: pd.Timestamp('2011-01-02 10:00'), 3: pd.Timestamp('2011-01-04 10:00')})
        expected = Series([Timestamp('2011-01-01 10:00'), Timestamp('2011-01-02 10:00'), Timestamp('2011-01-03 10:00'), Timestamp('2011-01-04 10:00')])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        idx = pd.DatetimeIndex(['2011-01-01 10:00', pd.NaT, '2011-01-03 10:00', pd.NaT], tz=tz)
        s = pd.Series(idx)
        assert s.dtype == f'datetime64[ns, {tz}]'
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna(pd.Timestamp('2011-01-02 10:00'))
        expected = Series([Timestamp('2011-01-01 10:00', tz=tz), Timestamp('2011-01-02 10:00'), Timestamp('2011-01-03 10:00', tz=tz), Timestamp('2011-01-02 10:00')])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna(pd.Timestamp('2011-01-02 10:00', tz=tz))
        idx = pd.DatetimeIndex(['2011-01-01 10:00', '2011-01-02 10:00', '2011-01-03 10:00', '2011-01-02 10:00'], tz=tz)
        expected = Series(idx)
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna(pd.Timestamp('2011-01-02 10:00', tz=tz).to_pydatetime())
        idx = pd.DatetimeIndex(['2011-01-01 10:00', '2011-01-02 10:00', '2011-01-03 10:00', '2011-01-02 10:00'], tz=tz)
        expected = Series(idx)
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna('AAA')
        expected = Series([Timestamp('2011-01-01 10:00', tz=tz), 'AAA', Timestamp('2011-01-03 10:00', tz=tz), 'AAA'], dtype=object)
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna({1: pd.Timestamp('2011-01-02 10:00', tz=tz), 3: pd.Timestamp('2011-01-04 10:00')})
        expected = Series([Timestamp('2011-01-01 10:00', tz=tz), Timestamp('2011-01-02 10:00', tz=tz), Timestamp('2011-01-03 10:00', tz=tz), Timestamp('2011-01-04 10:00')])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna({1: pd.Timestamp('2011-01-02 10:00', tz=tz), 3: pd.Timestamp('2011-01-04 10:00', tz=tz)})
        expected = Series([Timestamp('2011-01-01 10:00', tz=tz), Timestamp('2011-01-02 10:00', tz=tz), Timestamp('2011-01-03 10:00', tz=tz), Timestamp('2011-01-04 10:00', tz=tz)])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna(Timestamp('20130101'))
        expected = Series([Timestamp('2011-01-01 10:00', tz=tz), Timestamp('2013-01-01'), Timestamp('2011-01-03 10:00', tz=tz), Timestamp('2013-01-01')])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
        result = s.fillna(Timestamp('20130101', tz='US/Pacific'))
        expected = Series([Timestamp('2011-01-01 10:00', tz=tz), Timestamp('2013-01-01', tz='US/Pacific'), Timestamp('2011-01-03 10:00', tz=tz), Timestamp('2013-01-01', tz='US/Pacific')])
        tm.assert_series_equal(expected, result)
        tm.assert_series_equal(pd.isna(s), null_loc)
    df = pd.Series([pd.Timestamp('2012-11-11 00:00:00+01:00'), pd.NaT])
    exp = pd.Series([pd.Timestamp('2012-11-11 00:00:00+01:00'), pd.Timestamp('2012-11-11 00:00:00+01:00')])
    tm.assert_series_equal(df.fillna(method='pad'), exp)
    df = pd.Series([pd.NaT, pd.Timestamp('2012-11-11 00:00:00+01:00')])
    exp = pd.Series([pd.Timestamp('2012-11-11 00:00:00+01:00'), pd.Timestamp('2012-11-11 00:00:00+01:00')])
    tm.assert_series_equal(df.fillna(method='bfill'), exp)