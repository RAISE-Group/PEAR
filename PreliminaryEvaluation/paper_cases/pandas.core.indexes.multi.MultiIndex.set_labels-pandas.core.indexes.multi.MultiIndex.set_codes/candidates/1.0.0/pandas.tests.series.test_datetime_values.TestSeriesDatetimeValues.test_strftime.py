def test_strftime(self):
    s = Series(date_range('20130101', periods=5))
    result = s.dt.strftime('%Y/%m/%d')
    expected = Series(['2013/01/01', '2013/01/02', '2013/01/03', '2013/01/04', '2013/01/05'])
    tm.assert_series_equal(result, expected)
    s = Series(date_range('2015-02-03 11:22:33.4567', periods=5))
    result = s.dt.strftime('%Y/%m/%d %H-%M-%S')
    expected = Series(['2015/02/03 11-22-33', '2015/02/04 11-22-33', '2015/02/05 11-22-33', '2015/02/06 11-22-33', '2015/02/07 11-22-33'])
    tm.assert_series_equal(result, expected)
    s = Series(period_range('20130101', periods=5))
    result = s.dt.strftime('%Y/%m/%d')
    expected = Series(['2013/01/01', '2013/01/02', '2013/01/03', '2013/01/04', '2013/01/05'])
    tm.assert_series_equal(result, expected)
    s = Series(period_range('2015-02-03 11:22:33.4567', periods=5, freq='s'))
    result = s.dt.strftime('%Y/%m/%d %H-%M-%S')
    expected = Series(['2015/02/03 11-22-33', '2015/02/03 11-22-34', '2015/02/03 11-22-35', '2015/02/03 11-22-36', '2015/02/03 11-22-37'])
    tm.assert_series_equal(result, expected)
    s = Series(date_range('20130101', periods=5))
    s.iloc[0] = pd.NaT
    result = s.dt.strftime('%Y/%m/%d')
    expected = Series([np.nan, '2013/01/02', '2013/01/03', '2013/01/04', '2013/01/05'])
    tm.assert_series_equal(result, expected)
    datetime_index = date_range('20150301', periods=5)
    result = datetime_index.strftime('%Y/%m/%d')
    expected = Index(['2015/03/01', '2015/03/02', '2015/03/03', '2015/03/04', '2015/03/05'], dtype=np.object_)
    tm.assert_index_equal(result, expected)
    period_index = period_range('20150301', periods=5)
    result = period_index.strftime('%Y/%m/%d')
    expected = Index(['2015/03/01', '2015/03/02', '2015/03/03', '2015/03/04', '2015/03/05'], dtype='=U10')
    tm.assert_index_equal(result, expected)
    s = Series([datetime(2013, 1, 1, 2, 32, 59), datetime(2013, 1, 2, 14, 32, 1)])
    result = s.dt.strftime('%Y-%m-%d %H:%M:%S')
    expected = Series(['2013-01-01 02:32:59', '2013-01-02 14:32:01'])
    tm.assert_series_equal(result, expected)
    s = Series(period_range('20130101', periods=4, freq='H'))
    result = s.dt.strftime('%Y/%m/%d %H:%M:%S')
    expected = Series(['2013/01/01 00:00:00', '2013/01/01 01:00:00', '2013/01/01 02:00:00', '2013/01/01 03:00:00'])
    s = Series(period_range('20130101', periods=4, freq='L'))
    result = s.dt.strftime('%Y/%m/%d %H:%M:%S.%l')
    expected = Series(['2013/01/01 00:00:00.000', '2013/01/01 00:00:00.001', '2013/01/01 00:00:00.002', '2013/01/01 00:00:00.003'])
    tm.assert_series_equal(result, expected)